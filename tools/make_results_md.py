#!/usr/bin/env python3
"""Generate RESULTS.md from the JSON files in results/ -- every number in RESULTS.md is read from a JSON
here, so the two cannot drift. It also refreshes the headline table in README.md (between the results markers).
usage: python3 tools/make_results_md.py [OUT_DIR]   (default: rewrites RESULTS.md and README.md at the repo root;
       with OUT_DIR it writes both there instead and leaves the repo untouched -- tools/check_results.py uses that)"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = sys.argv[1] if len(sys.argv) > 1 else ROOT
J = lambda p: json.load(open(os.path.join(ROOT, "results", p)))
BOARDS = [("RTX 5090", "5090"), ("Jetson AGX Thor", "thor"), ("Jetson AGX Orin", "orin")]
E = {b: J(f"speed/groot_{k}_fulltrt_e2e_2026-10-12.json") for b, k in BOARDS}
SW, SWE = J("speed/n15_5090_denoise_fulltrt_2026-10-12.json"), J("speed/n15_5090_denoise_eager_2026-09-23.json")
ST = J("speed/n15_5090_stagetime_fulltrt_2026-10-12.json")
ENG, ARMS, HY = J("speed/engine_stage_times_2026-08-27.json"), J("speed/arms_2v4_2026-10-11.json"), J("speed/hybrid_e2e_2026-09-06.json")
CL = J("accuracy/closed_loop_summary_2026-09-18.json")
f1, f2 = (lambda x: f"{x:.1f}"), (lambda x: f"{x:.2f}")
L = []
w = L.append

w("# Results\n")
w("Generated by `tools/make_results_md.py` from the JSON files in `results/` — every number below is read from those files.\n")
w("**Provenance tags.** **MEASURED** = we ran it (where [docs/BENCHMARKS.md](docs/BENCHMARKS.md) says *regenerates*, the raw data is in `results/` and `tools/check_results.py` rebuilds the number; *published record* means the record is published as measured, without its raw data). **DERIVED** = computed from measurements (labelled). "
  "**SOURCED** = someone else's published number (labelled, never mixed into a MEASURED comparison).\n")
w("**Hardware.** RTX 5090 desktop (x86); Jetson AGX Thor (JetPack 7.2.1, MAXN power mode); Jetson AGX Orin 64 GB (JetPack 6, MAXN power mode). "
  "Whether clocks were pinned (`jetson_clocks`, `nvidia-smi -lgc`) differs per run; it is stated in §1-3 and their records, "
  "and was not recorded for §4, §6 and §7. "
  "**TensorRT versions:** §1-2 use TensorRT 11.2 (5090), 10.13 (Thor, NGC container) and 10.3 (Orin, JetPack); §3 and §4 use 10.16 on the 5090 "
  "and Thor and 10.3 on Orin; §6 uses 10.16 on Thor and 10.3 on Orin (the 5090's version is not recorded there); §7 uses 11.2. Software versions are in each record and in `setup/`.\n")
w("**Different inputs.** §1-3 time the *base* GR00T N1.5 model on one recorded frame from NVIDIA's "
  "simulated GR1 PickNPlace demo (26 joints: arms + hands); §4 and §7 time single engines on synthetic zero/random inputs of the same shapes. The closed loop (§5) runs the RoboCasa *post-trained* model on the milk task "
  "(29 joints: arms + hands + waist). GR00T pads both to 32 action dimensions internally.\n")

# ---------------------------------------------------------------- speed
w("## 1. Speed: the whole policy call, three compilation levels (MEASURED, 2026-10-12)\n")
w("One `policy.get_action()` on one recorded frame of NVIDIA's simulated GR1 PickNPlace demo (camera image + joint state + instruction) → a 16-step action chunk, "
  "4 denoise steps, fp16 TensorRT engines. One process per board alternates eager / hybrid / full-TensorRT blocks "
  "(eager, hybrid, full, hybrid, full, eager; 20 timed calls after 5 warm-up per block) so session drift cancels; two independent "
  "engine builds per board. *Hybrid* = only ViT, LLM and DiT as TensorRT engines, the rest PyTorch eager. *Full TensorRT* = NVIDIA's own "
  "N1.5 deployment path (`deployment_scripts/trt_model_forward`), all 7 modules as engines.\n")
w("| Board | TensorRT | Engines alone, ViT+LLM+4×DiT (DERIVED) | Eager | Hybrid | **Full TensorRT** | Full vs hybrid | Host + glue, full |")
w("|---|---|---|---|---|---|---|---|")
for b, _ in BOARDS:
    r = E[b]["results"]; es = r["engine_sum_standalone_ms_DERIVED"]["vit_llm_4xdit"]
    w(f"| {b} | {E[b]['trt']} | {f2(es)} ms = {f1(1000/es)} Hz | {f1(r['eager_bf16_e2e_ms_same_session']['median'])} ms "
      f"| {f1(r['hybrid_e2e_ms_same_session']['median'])} ms = {f1(r['hybrid_hz_same_session'])} Hz "
      f"| **{f2(r['full_trt_e2e_ms']['median'])} ms = {f1(r['full_trt_hz'])} Hz** | {r['full_vs_hybrid_speedup']:.2f}× "
      f"| {f2(r['host_and_glue_ms_MEASURED']['full'])} ms |")
w("")
w("**Engine benchmarks overstate the robot's rate.** Share of the engine-alone rate lost by the whole call (same session):\n")
w("| Board | Hybrid | Full TensorRT |")
w("|---|---|---|")
for b, _ in BOARDS:
    rl = E[b]["results"]["rate_lost_vs_engine_sum_pct"]
    w(f"| {b} | −{rl['hybrid']:.1f}% | −{rl['full']:.1f}% |")
w("")
w("Host + glue = e2e − synced in-pipeline engine time: image transforms, pixel shuffle / projector / embedding merge, the Euler "
  "denoise loop, and 7 engine hand-offs, each followed by a stream sync (NVIDIA's `Engine.forward` syncs after every call). "
  "No CUDA graphs on this path; a fused export could do better — not measured.\n")
w("**Output check.** Full TensorRT vs eager bf16, same noise draw, per action key (rel_mae / abs_mae, build A):\n")
w("| Board | left_arm | right_arm | right_hand | left_hand (idle) | eager vs eager |")
w("|---|---|---|---|---|---|")
for b, _ in BOARDS:
    g = E[b]["gate"]["full_vs_eager"]; c = E[b]["gate"]["control_eager_vs_eager"]
    cell = lambda k: f"{g[k]['rel_mae']:.4f} / {g[k]['abs_mae']:.4f}"
    ctrl = max(v["rel_mae"] for v in c.values())
    w(f"| {b} | {cell('action.left_arm')} | {cell('action.right_arm')} | {cell('action.right_hand')} | {cell('action.left_hand')} | {ctrl:.1f} |")
w("")
w("The left hand is idle in this observation (|ref| mean ≈ 0.008), so its rel_mae is a small-denominator artifact; its abs_mae "
  "matches the other keys' fp16 floor.\n")
w("**Variance.** Full-TensorRT median per engine build: " + "; ".join(
    f"{b} {E[b]['build_variance']['full_e2e_median_per_build']}" for b, _ in BOARDS) +
  " ms. Expect ~1–10% build-to-build on other builds/versions: a single TensorRT build is a tactic lottery, so always build twice. "
  "Clocks: " + "; ".join(f"{b}: {E[b]['clocks']}" for b, _ in BOARDS) + ".\n")
w("Reproduce: `bash speed/run_board.sh <label>` ([docs/SPEED.md](docs/SPEED.md); Thor: inside `setup/thor_container.sh`). Records: "
  "`results/speed/groot_{5090,thor,orin}_fulltrt_e2e_2026-10-12.json`; raw: `results/speed/raw/res_*`. "
  "`speed/make_e2e_record.py` regenerates the records from the raw files exactly.\n")
w("<details><summary>Earlier hybrid-only measurement (2026-09-06)</summary>\n")
w("| Board | Hybrid e2e | Host + glue |")
w("|---|---|---|")
for b, v in HY["boards"].items():
    w(f"| {b} | {f2(v['hybrid_e2e_ms_median'])} ms = {f1(v['hybrid_hz'])} Hz | {f2(v['host_and_glue_ms'])} ms |")
w(f"\n{HY['status']}.\n</details>\n")

w("## 2. Denoise steps: cost vs solver deviation (RTX 5090, MEASURED)\n")
ld, lde = SW["latency_decomposition"], SWE["latency_decomposition"]
w(f"Steps swept 1→32 (+ a 64-step near-converged reference), 5 episodes × 3 noise seeds, matched noise.\n")
w(f"- **Full TensorRT (2026-10-12):** latency = **{ld['backbone_intercept_ms']:.2f} + {ld['per_denoise_step_ms']:.2f} ms × steps** "
  f"(r² = {ld['r2']}); {SW['clocks_pinned'].split(';')[0]}.")
w(f"- **PyTorch eager (2026-09-23):** latency = {lde['backbone_intercept_ms']:.1f} + {lde['per_denoise_step_ms']:.2f} ms × steps "
  f"(r² = {lde['r2']}); {SWE['clocks_pinned']}.\n")
w("| Steps | Full TensorRT latency | Deviation vs 64-step ref, full TensorRT | Deviation, eager |")
w("|---|---|---|---|")
for k in ["1", "2", "4", "8", "16", "32"]:
    w(f"| {k} | {f2(SW['latency_ms'][k]['median_ms'])} ms | {SW['deviation_vs_ref_pct'][k]['mean_pct']:.2f} ± {SW['deviation_vs_ref_pct'][k]['std_pct']:.2f}% "
      f"| {SWE['deviation_vs_ref_pct'][k]['mean_pct']:.2f} ± {SWE['deviation_vs_ref_pct'][k]['std_pct']:.2f}% |")
w("")
w(f"Deviation = rel-MAE of the 26-DoF × 16-step action chunk vs a 64-step reference on the same path (solver truncation, ~C/N: "
  f"C = {SW['deviation_1overN_fit']['C']} compiled, {SWE['deviation_1overN_fit']['C']} eager). It is **not** task success. "
  f"Build-to-build: per-step {[round(x, 3) for x in SW['build_variance']['per_step_ms']]} ms, max step-count spread "
  f"{SW['build_variance']['max_step_count_spread_pct']}%.\n")
fv = ST["fixed_vs_scaling"]
w(f"**Where the time goes at 4 steps (full TensorRT, instrumented):** fixed {fv['fixed_ms_at_any_step_count']} ms "
  f"(transforms {fv['fixed']['transform']}, ViT {fv['fixed']['vit']}, LLM {fv['fixed']['llm']}, VL self-attn {fv['fixed']['vlln_vl_self_attention']}, "
  f"other {fv['fixed']['other']} ms) + {fv['per_step_ms']} ms per step (DiT {fv['scales_per_step']['dit_total']}, Euler-loop glue "
  f"{fv['scales_per_step']['head_torch_glue']}, encoder {fv['scales_per_step']['action_encoder_total']}, decoder "
  f"{fv['scales_per_step']['action_decoder_total']} ms). Host + glue grows with steps on this path: {fv['host_and_glue']['intercept_ms']} + "
  f"{fv['host_and_glue']['per_step_ms']} ms/step.\n")
w("Reproduce: `bash speed/run_denoise_sweep.sh`. Records: `results/speed/n15_5090_{denoise,stagetime}_{fulltrt,eager}_*.json`.\n")

w("## 3. Engines timed alone (MEASURED, 2026-08-27; NVIDIA figures SOURCED)\n")
w("| Board | TensorRT | ViT | LLM | DiT step | ViT + LLM + 4×DiT |")
w("|---|---|---|---|---|---|")
for r in ENG["rows"]:
    w(f"| {r['board']} | {r['trt']} | {r['vit_ms']} | {r['llm_ms']} | {r['dit_step_ms']} | {r['stage_sum_ms']} ms |")
