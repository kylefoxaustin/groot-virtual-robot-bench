w(f"\nAgainst NVIDIA's published Orin numbers (same TensorRT major version, SOURCED): theirs {o['nvidia']['stage_sum']} ms vs ours "
  f"{o['ours']['stage_sum']} ms ({o['total_delta_pct']}%; per stage {o['per_stage_delta_pct']}%). The Thor row is not a validation "
  f"(TensorRT versions differ). Clocks: `jetson_clocks` was **not** applied on either Jetson for these runs, while NVIDIA's published figures use it, so the Orin agreement is if anything conservative. Build engines **strongly typed**: {ENG['fp16_build_trap']['what']}\n")

w("## 4. Two arms vs four arms (MEASURED, 2026-10-11)\n")
